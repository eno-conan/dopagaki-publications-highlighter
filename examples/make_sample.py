"""ダミーの書籍PDF（examples/sample-book/sample-book.pdf）を作る。

内容は、このツールの説明用に書いた架空の文章。実在の書籍・記事とは関係がない。
使い方（app/ で実行）: uv run python ../examples/make_sample.py
"""

from pathlib import Path

import pymupdf

OUT = Path(__file__).resolve().parent / "sample-book" / "sample-book.pdf"

# (章の見出し, その章のページごとの本文)
CHAPTERS = [
    (
        "第1章 キャッシュの基本",
        [
            [
                "キャッシュとは、よく使うデータを、取り出しやすい場所に一時的に置いておく仕組みである。",
                "同じ問い合わせが繰り返されるとき、毎回元のデータを調べ直すより速く答えられる。",
                "ただし、置いたデータが古くなると、元のデータと食い違うことがある。",
                "この食い違いを防ぐために、データに有効期限を付けるのが基本的な方針である。",
                "有効期限を長くしすぎると、古い値を返し続けてしまうので注意が必要である。",
                "サンプルのアプリでは、有効期限を60秒にして、読み込みの回数を約8割減らした。",
            ],
            [
                "キャッシュに置くデータは、読む回数が多く、書き換えが少ないものを選ぶ。",
                "頻繁に書き換わるデータをキャッシュすると、更新のたびに破棄が必要になり、効果が薄い。",
                "まず計測し、遅い箇所を確かめてから導入することが重要である。",
                "計測せずに導入すると、複雑さだけが増えて、速くならないことがある。",
            ],
        ],
    ),
    (
        "第2章 キャッシュの破棄",
        [
            [
                "キャッシュの破棄とは、古くなったデータを取り除いて、最新の状態に保つことである。",
                "破棄の方法には、有効期限で自動的に消す方法と、更新のたびに手動で消す方法がある。",
                "手動で消す方法は正確だが、消し忘れると古い値が残り続けるという限界がある。",
                "そのため、有効期限と手動の破棄を組み合わせて使うのが実践的である。",
                "更新した直後は、必ず該当するキャッシュを破棄するようにする。",
            ],
            [
                "複数のサーバーで同じデータを持つ場合、片方だけを破棄すると値が食い違う。",
                "共有の置き場所にキャッシュを集めると、この食い違いを避けられる。",
                "一方で、共有の置き場所が止まると全体に影響するので、冗長にしておく。",
                "障害のときは、キャッシュを使わずに元のデータへ直接問い合わせる逃げ道を用意する。",
            ],
        ],
    ),
    (
        "第3章 運用と監視",
        [
            [
                "ヒット率とは、問い合わせのうち、キャッシュで答えられた割合のことである。",
                "ヒット率が低いままなら、置くデータの選び方か、有効期限が合っていない可能性がある。",
                "サンプルのアプリでは、ヒット率が90％を下回ったら通知する設定にした。",
                "メモリを使い切るとキャッシュが作動しなくなるので、上限を決めておくことが重要である。",
                "上限を超えたときは、最も古く使われたものから順に捨てる方針が一般的である。",
            ],
            [
                "導入の前後で、応答時間とヒット率を記録し、効果を数字で確かめる。",
                "効果が小さいキャッシュは、複雑さに見合わないので、思い切って外す。",
                "運用の手順は文書にして、誰でも破棄や再起動ができるようにしておく。",
                "定期的に設定を見直し、データの使われ方の変化に合わせて有効期限を調整する。",
            ],
        ],
    ),
]


def main() -> None:
    doc = pymupdf.open()
    font = pymupdf.Font("cjk")
    toc: list[list] = []
    for title, pages in CHAPTERS:
        toc.append([1, title, len(doc) + 1])
        for lines in pages:
            page = doc.new_page()
            page.insert_font(fontname="cjk", fontbuffer=font.buffer)
            page.insert_text((50, 70), title, fontname="cjk", fontsize=16)
            for i, line in enumerate(lines):
                page.insert_text((50, 120 + 28 * i), line, fontname="cjk", fontsize=10)
    doc.set_toc(toc)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    doc.close()
    print(f"作成: {OUT}")


if __name__ == "__main__":
    main()
